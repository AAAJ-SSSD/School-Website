const $ = (s, el = document) => el.querySelector(s);
const $$ = (s, el = document) => [...el.querySelectorAll(s)];
const root = document.documentElement;

/* ---------- Language ---------- */
function setLang(lang) {
  $$("[data-i18n]").forEach(el => {
    if (el.dataset.en === undefined) el.dataset.en = el.innerHTML;
    const text = lang === "ar" ? AR[el.dataset.i18n] : el.dataset.en;
    if (text !== undefined) el.innerHTML = text;
  });
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";
  $("#langBtn").textContent = lang === "ar" ? "English" : "عربي";
  document.title = lang === "ar" ? "أكاديمية عالم جدة" : "Jeddah World Academy";
  try { localStorage.setItem("jwa-lang", lang); } catch (e) {}
}
$("#langBtn").addEventListener("click", () => setLang(root.lang === "ar" ? "en" : "ar"));
try { if (localStorage.getItem("jwa-lang") === "ar") setLang("ar"); } catch (e) {}

/* ---------- Header & mobile nav ---------- */
const header = $("#header");
const nav = $("#nav");
const burger = $("#burger");
const toTop = $("#toTop");

function onScroll() {
  const y = window.scrollY;
  header.classList.toggle("is-scrolled", y > 10);
  toTop.classList.toggle("is-visible", y > 600);
}
window.addEventListener("scroll", onScroll, { passive: true });
onScroll();

burger.addEventListener("click", () => {
  const open = nav.classList.toggle("is-open");
  burger.classList.toggle("is-open", open);
  burger.setAttribute("aria-expanded", open);
});

const isMobile = () => window.matchMedia("(max-width: 1100px)").matches;
$$(".has-drop > a").forEach(a => {
  a.addEventListener("click", e => {
    if (!isMobile()) return;
    e.preventDefault();
    a.parentElement.classList.toggle("is-open");
  });
});
$$(".nav .drop a, .nav > ul > li:not(.has-drop) > a").forEach(a =>
  a.addEventListener("click", () => {
    nav.classList.remove("is-open");
    burger.classList.remove("is-open");
    burger.setAttribute("aria-expanded", "false");
  })
);

/* Highlight the nav link of the section in view */
const navLinks = $$(".nav > ul > li > a");
const spy = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    navLinks.forEach(l => l.classList.toggle("is-active", l.getAttribute("href") === "#" + entry.target.id));
  });
}, { rootMargin: "-45% 0px -50% 0px" });
$$("main section[id]").forEach(s => spy.observe(s));

/* ---------- Program tabs ---------- */
$$(".tab").forEach(tab => {
  tab.addEventListener("click", () => {
    $$(".tab").forEach(t => t.classList.toggle("is-active", t === tab));
    $$(".panel").forEach(p => p.classList.toggle("is-active", p.id === tab.dataset.tab));
  });
});

/* ---------- Reveal + counters ---------- */
function countUp(el) {
  const target = +el.dataset.to;
  const start = performance.now();
  const dur = 1600;
  (function tick(now) {
    const p = Math.min((now - start) / dur, 1);
    el.textContent = Math.round(target * (1 - Math.pow(1 - p, 3)));
    if (p < 1) requestAnimationFrame(tick);
  })(start);
}

const revealer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    const el = entry.target;
    const siblings = $$(".reveal", el.parentElement);
    el.style.transitionDelay = Math.min(siblings.indexOf(el), 4) * 90 + "ms";
    el.classList.add("is-visible");
    // Hand transitions back to the element's own hover styles once revealed
    setTimeout(() => {
      el.classList.remove("reveal", "is-visible");
      el.style.transitionDelay = "";
    }, 1300);
    $$(".count", el).forEach(countUp);
    revealer.unobserve(el);
  });
}, { threshold: 0.15 });
$$(".reveal").forEach(el => revealer.observe(el));

/* ---------- Contact form ---------- */
$("#contactForm").addEventListener("submit", e => {
  e.preventDefault();
  const form = e.target;
  const note = $("#formNote");
  const msgs = MSG[root.lang] || MSG.en;
  let ok = true;
  ["name", "phone", "email"].forEach(n => {
    const input = form.elements[n];
    const valid = input.value.trim() && input.checkValidity();
    input.classList.toggle("invalid", !valid);
    if (!valid) ok = false;
  });
  note.style.color = ok ? "#4d8a22" : "#e5484d";
  note.textContent = ok ? msgs.ok : msgs.err;
  if (ok) form.reset();
});

